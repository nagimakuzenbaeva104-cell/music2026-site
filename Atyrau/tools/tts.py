"""Generate per-sentence Kazakh narration with Piper and write src/narration.ts.

Usage: tts-venv/bin/python tools/tts.py <voice.onnx> [speaker_id]
"""
import json, math, sys, wave
from pathlib import Path
from piper import PiperVoice, SynthesisConfig

root = Path(__file__).resolve().parent.parent
voice = PiperVoice.load(sys.argv[1])
cfg = SynthesisConfig(speaker_id=int(sys.argv[2]) if len(sys.argv) > 2 else 1, length_scale=1.08)
out_dir = root / "public" / "voice"
out_dir.mkdir(parents=True, exist_ok=True)

FPS, FADE = 30, 20  # must match src/Video.tsx
LEAD, GAP, TAIL = 0.6, 0.4, 1.4  # seconds of silence around/between lines

result = []
start = 0
for scene in json.loads((root / "tools" / "narration.json").read_text()):
    lines = []
    for i, (display, spoken) in enumerate(scene["lines"]):
        name = f"{scene['id']}_{i}.wav"
        with wave.open(str(out_dir / name), "wb") as w:
            voice.synthesize_wav(spoken, w, syn_config=cfg)
        with wave.open(str(out_dir / name)) as r:
            dur = r.getnframes() / r.getframerate()
        lines.append({"text": display, "file": f"voice/{name}", "sec": round(dur, 3)})
        print(f"{name}: {dur:.2f}s")
    speech = LEAD + sum(l["sec"] for l in lines) + GAP * (len(lines) - 1) + TAIL
    dur = max(scene["minSec"] * FPS, math.ceil(speech * FPS))
    t = LEAD
    for l in lines:
        l["from"] = start + round(t * FPS)
        l["frames"] = math.ceil(l["sec"] * FPS)
        t += l["sec"] + GAP
    result.append({"id": scene["id"], "durationInFrames": dur, "lines": lines})
    start += dur - FADE

total = start + FADE

def ts(frame):
    ms = round(frame / FPS * 1000)
    return f"{ms // 3600000:02}:{ms // 60000 % 60:02}:{ms // 1000 % 60:02},{ms % 1000:03}"

srt, n = [], 0
for scene in result:
    for l in scene["lines"]:
        n += 1
        srt.append(f"{n}\n{ts(l['from'])} --> {ts(l['from'] + l['frames'])}\n{l['text']}\n")
(root / "atyrau.kk.srt").write_text("\n".join(srt))

(root / "src" / "narration.ts").write_text(
    "// Generated by tools/tts.py. Do not edit by hand.\n"
    "// `from` is the absolute frame in the full video; `frames` is the line's length.\n"
    "export type Line = { text: string; file: string; sec: number; from: number; frames: number };\n"
    "export type SceneTiming = { id: string; durationInFrames: number; lines: Line[] };\n"
    f"export const TOTAL_FRAMES = {total};\n"
    f"export const NARRATION: SceneTiming[] = {json.dumps(result, ensure_ascii=False, indent=2)};\n"
)
