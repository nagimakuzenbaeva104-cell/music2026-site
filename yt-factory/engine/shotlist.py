"""Список необходимых кадров -> assets/README.md (генерируется из сценария и тайминга)."""
from pathlib import Path

ZONES = {  # доли высоты кадра 9:16, где лежит текст (см. layout.py)
    "hero": (0.30, 0.46),
    "subs": (0.57, 0.72),
}


def write(project_dir, proj, brand, tl):
    assets = Path(project_dir) / "assets"
    assets.mkdir(exist_ok=True)
    F = brand["formats"][tl["format"]]
    T = brand["transitions"]["duration"]
    rows, details = [], []
    for s in tl["scenes"]:
        sid = int(s["id"])
        need = (s["end"] - s["start"]) + T
        status = f"✅ `{s['asset']}`" if s["asset"] else "⬜ нет"
        query = (s.get("asset_hint") or "").split(":", 1)[-1].strip()
        rows.append(f"| {sid} | `s{sid:02d}.mp4` | {s['start']:.1f}–{s['end']:.1f} | "
                    f"≥ {need + 1:.0f} с | {s['visual']} | `{query}` | {status} |")
        txt = " ".join(w["w"] for ch in s["chunks"] for w in ch["words"])
        details += [
            f"### s{sid:02d} — {s['visual']}", "",
            f"- В кадре звучит: «{s['say']}»",
            f"- На экране: hero **{s['hero'] or '—'}** + субтитры «{txt}»",
            f"- Длина клипа: не меньше **{need:.1f} с** (лучше {need + 1:.0f}+ с; короче — будет зациклен)",
            f"- Поиск (Pexels / свой архив): `{query}`",
            "",
        ]
    lines = [
        f"# Кадры для «{proj.get('title')}»",
        "",
        "Файл сгенерирован командой `storyboard` — правьте сценарий (`scenes.yaml`), а не этот файл.",
        "",
        "## Как добавить кадр",
        "",
        "1. Назовите файл по номеру сцены: `s01.mp4`, `s02.jpg` … (mp4/mov/webm или jpg/png/webp).",
        "2. Положите его в эту папку `assets/`. Движок подхватит его сам.",
        "3. Музыка: `music.mp3` в эту же папку (YouTube Audio Library). Без файла — видео без музыки.",
        "4. Видео и аудио из `assets/` в git не попадают (`.gitignore`).",
        "",
        "## Список",
        "",
        "| Сцена | Файл | Время, с | Длина | Что в кадре | Поисковый запрос | Статус |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        "## Требования ко всем кадрам",
        "",
        f"- **Формат:** вертикальный 9:16, от {F['w']}×{F['h']}. Горизонтальный 16:9 тоже можно, "
        "но в кадр попадёт только центральная треть ширины (≈32%) — главный объект должен быть в центре.",
        f"- **Свободные зоны:** {ZONES['hero'][0]:.0%}–{ZONES['hero'][1]:.0%} высоты — крупная цифра "
        f"(hero), {ZONES['subs'][0]:.0%}–{ZONES['subs'][1]:.0%} — субтитры. Лица и важные объекты "
        "в этих полосах будут закрыты текстом. Низ кадра (~25%) и правый край перекрывает интерфейс "
        "YouTube.",
        "- **Стиль:** тёмный, кинематографичный, тёплый свет (золото/янтарь) и холодные синие тени — "
        "под палитру канала. Медленное движение камеры, без резких рывков.",
        "- **Без реальных людей сюжета:** не используйте кадры, где можно принять человека за "
        "Джеффа Безоса, и не генерируйте его лицо. Только символические кадры (город, гараж, книги, "
        "биржа).",
        "- **Не случайные кадры:** каждый клип должен показывать то, о чём говорится в сцене.",
        "- **Лицензия:** только кадры, которые вы вправе использовать (Pexels License, свои съёмки).",
        "  Сохраняйте ссылку на источник каждого клипа — пригодится при споре по авторским правам.",
        "",
        "## Детали по сценам",
        "",
        *details,
    ]
    (assets / "README.md").write_text("\n".join(lines), encoding="utf-8")
